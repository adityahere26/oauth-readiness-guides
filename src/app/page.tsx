import { Generator } from "@/components/Generator";
import { GuideCard } from "@/components/ui";
import { curatedGuides } from "@/data/curated";
import { listGenerated } from "@/lib/store";

export const dynamic = "force-dynamic";

export default async function Home() {
  const generated = await listGenerated().catch(() => []);
  const curated = [...curatedGuides].sort((a, b) => a.difficulty.score - b.difficulty.score);

  return (
    <div>
      <section className="py-6">
        <h1 className="max-w-2xl text-3xl font-bold tracking-tight sm:text-4xl">How long until your users can connect an app?</h1>
        <p className="mt-3 max-w-2xl text-zinc-600 dark:text-zinc-400">
          Before launch, your agent needs its own OAuth app with each provider. Each guide shows how hard that is, how long it takes, what approval is
          needed, and which steps an agent can do for you. Every claim is labeled by how we know it.
        </p>
        <div className="mt-6 max-w-2xl">
          <Generator />
          <p className="mt-2 text-xs text-zinc-500">
            Not in the library? An agent researches the provider&apos;s docs live, probes its OAuth endpoints, and writes a shareable guide (about 30–90 s).
          </p>
        </div>
      </section>

      <section className="mt-6">
        <div className="mb-3 flex items-baseline justify-between">
          <h2 className="text-lg font-semibold">Curated library</h2>
          <span className="text-xs text-zinc-500">Sorted easiest → hardest · reviewed against sources</span>
        </div>
        <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
          {curated.map((g) => (
            <GuideCard key={g.slug} g={g} />
          ))}
        </div>
      </section>

      {generated.length > 0 && (
        <section className="mt-10">
          <h2 className="mb-3 text-lg font-semibold">Recently generated by the agent</h2>
          <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
            {generated.map((g) => (
              <GuideCard key={g.slug} g={g} />
            ))}
          </div>
        </section>
      )}
    </div>
  );
}
